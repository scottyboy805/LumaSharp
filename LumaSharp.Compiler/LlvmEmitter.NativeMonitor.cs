namespace LumaSharp.Compiler;

internal sealed partial class LlvmEmitter
{
	private void EmitNativeMonitorRuntime()
	{
		const int bucketCount = 4096;
		var sizeType = compilation.NativePointerSize == 8 ? "i64" : "i32";
		var entrySize = compilation.NativePointerSize == 8 ? "40" : "24";
		AppendDeclarationIfMissing($"declare ptr @malloc({sizeType})");
		AppendDeclarationIfMissing("declare void @free(ptr)");

		_output.AppendLine("%luma.monitor_entry = type { ptr, ptr, i32, ptr, i32, i32 }");
		_output.AppendLine("@luma_monitor_identity = internal thread_local global i8 0");
		_output.AppendLine("@luma_monitor_table_gate = internal global i32 0");
		_output.AppendLine($"@luma_monitor_buckets = internal global [{bucketCount} x ptr] zeroinitializer");

		_output.AppendLine("define internal void @luma_monitor_table_lock() {");
		_output.AppendLine("entry:");
		_output.AppendLine("  br label %acquire");
		_output.AppendLine("acquire:");
		_output.AppendLine("  %attempt = cmpxchg ptr @luma_monitor_table_gate, i32 0, i32 1 acquire monotonic");
		_output.AppendLine("  %locked = extractvalue { i32, i1 } %attempt, 1");
		_output.AppendLine("  br i1 %locked, label %done, label %wait");
		_output.AppendLine("wait:");
		_output.AppendLine("  call void @luma_thread_sleep(i32 1)");
		_output.AppendLine("  br label %acquire");
		_output.AppendLine("done:");
		_output.AppendLine("  ret void");
		_output.AppendLine("}");
		_output.AppendLine("define internal void @luma_monitor_table_unlock() {");
		_output.AppendLine("entry:");
		_output.AppendLine("  store atomic i32 0, ptr @luma_monitor_table_gate release, align 4");
		_output.AppendLine("  ret void");
		_output.AppendLine("}");

		_output.AppendLine("define internal ptr @luma_monitor_find(ptr %object, i1 %create) {");
		_output.AppendLine("entry:");
		_output.AppendLine("  call void @luma_monitor_table_lock()");
		_output.AppendLine($"  %raw = ptrtoint ptr %object to {sizeType}");
		_output.AppendLine($"  %hash = urem {sizeType} %raw, {bucketCount}");
		_output.AppendLine("  %bucket.index = trunc " + sizeType + " %hash to i32");
		_output.AppendLine($"  %bucket.address = getelementptr [{bucketCount} x ptr], ptr @luma_monitor_buckets, i32 0, i32 %bucket.index");
		_output.AppendLine("  %first = load ptr, ptr %bucket.address");
		_output.AppendLine("  br label %lookup");
		_output.AppendLine("lookup:");
		_output.AppendLine("  %current = phi ptr [ %first, %entry ], [ %next, %probe ]");
		_output.AppendLine("  %current.null = icmp eq ptr %current, null");
		_output.AppendLine("  br i1 %current.null, label %absent, label %compare");
		_output.AppendLine("compare:");
		_output.AppendLine("  %current.object.address = getelementptr %luma.monitor_entry, ptr %current, i32 0, i32 0");
		_output.AppendLine("  %current.object = load ptr, ptr %current.object.address");
		_output.AppendLine("  %same.object = icmp eq ptr %current.object, %object");
		_output.AppendLine("  br i1 %same.object, label %found, label %probe");
		_output.AppendLine("probe:");
		_output.AppendLine("  %next.address = getelementptr %luma.monitor_entry, ptr %current, i32 0, i32 1");
		_output.AppendLine("  %next = load ptr, ptr %next.address");
		_output.AppendLine("  br label %lookup");
		_output.AppendLine("found:");
		_output.AppendLine("  br i1 %create, label %increment.users, label %return.found");
		_output.AppendLine("increment.users:");
		_output.AppendLine("  %users.address = getelementptr %luma.monitor_entry, ptr %current, i32 0, i32 5");
		_output.AppendLine("  %users = load i32, ptr %users.address");
		_output.AppendLine("  %users.next = add i32 %users, 1");
		_output.AppendLine("  store i32 %users.next, ptr %users.address");
		_output.AppendLine("  br label %return.found");
		_output.AppendLine("return.found:");
		_output.AppendLine("  call void @luma_monitor_table_unlock()");
		_output.AppendLine("  ret ptr %current");
		_output.AppendLine("absent:");
		_output.AppendLine("  br i1 %create, label %allocate.entry, label %return.missing");
		_output.AppendLine("allocate.entry:");
		_output.AppendLine($"  %new.entry = call ptr @malloc({sizeType} {entrySize})");
		_output.AppendLine("  %allocation.failed = icmp eq ptr %new.entry, null");
		_output.AppendLine("  br i1 %allocation.failed, label %return.missing, label %initialize.entry");
		_output.AppendLine("initialize.entry:");
		_output.AppendLine("  %new.object.address = getelementptr %luma.monitor_entry, ptr %new.entry, i32 0, i32 0");
		_output.AppendLine("  store ptr %object, ptr %new.object.address");
		_output.AppendLine("  %new.next.address = getelementptr %luma.monitor_entry, ptr %new.entry, i32 0, i32 1");
		_output.AppendLine("  store ptr %first, ptr %new.next.address");
		_output.AppendLine("  %new.state.address = getelementptr %luma.monitor_entry, ptr %new.entry, i32 0, i32 2");
		_output.AppendLine("  store i32 0, ptr %new.state.address");
		_output.AppendLine("  %new.owner.address = getelementptr %luma.monitor_entry, ptr %new.entry, i32 0, i32 3");
		_output.AppendLine("  store ptr null, ptr %new.owner.address");
		_output.AppendLine("  %new.depth.address = getelementptr %luma.monitor_entry, ptr %new.entry, i32 0, i32 4");
		_output.AppendLine("  store i32 0, ptr %new.depth.address");
		_output.AppendLine("  %new.users.address = getelementptr %luma.monitor_entry, ptr %new.entry, i32 0, i32 5");
		_output.AppendLine("  store i32 1, ptr %new.users.address");
		_output.AppendLine("  store ptr %new.entry, ptr %bucket.address");
		_output.AppendLine("  call void @luma_monitor_table_unlock()");
		_output.AppendLine("  ret ptr %new.entry");
		_output.AppendLine("return.missing:");
		_output.AppendLine("  call void @luma_monitor_table_unlock()");
		_output.AppendLine("  ret ptr null");
		_output.AppendLine("}");

		_output.AppendLine("define internal void @luma_monitor_enter(ptr %object) {");
		_output.AppendLine("entry:");
		_output.AppendLine("  call void @luma_thread_critical_enter()");
		_output.AppendLine("  %monitor = call ptr @luma_monitor_find(ptr %object, i1 true)");
		_output.AppendLine("  %allocation.failed = icmp eq ptr %monitor, null");
		_output.AppendLine("  br i1 %allocation.failed, label %out.of.memory, label %get.monitor");
		_output.AppendLine("out.of.memory:");
		_output.AppendLine("  call void @luma_thread_critical_exit()");
		_output.AppendLine("  call void @luma_raise_out_of_memory()");
		_output.AppendLine("  ret void");
		_output.AppendLine("get.monitor:");
		_output.AppendLine("  %state.address = getelementptr %luma.monitor_entry, ptr %monitor, i32 0, i32 2");
		_output.AppendLine("  %owner.address = getelementptr %luma.monitor_entry, ptr %monitor, i32 0, i32 3");
		_output.AppendLine("  %depth.address = getelementptr %luma.monitor_entry, ptr %monitor, i32 0, i32 4");
		_output.AppendLine("  %owner = load atomic ptr, ptr %owner.address acquire, align " + compilation.NativePointerSize);
		_output.AppendLine("  %is.owner = icmp eq ptr %owner, @luma_monitor_identity");
		_output.AppendLine("  br i1 %is.owner, label %recursive, label %acquire.start");
		_output.AppendLine("recursive:");
		_output.AppendLine("  %old.depth = load i32, ptr %depth.address");
		_output.AppendLine("  %next.depth = add i32 %old.depth, 1");
		_output.AppendLine("  store i32 %next.depth, ptr %depth.address");
		_output.AppendLine("  ret void");
		_output.AppendLine("acquire.start:");
		_output.AppendLine("  br label %acquire");
		_output.AppendLine("acquire:");
		_output.AppendLine("  %attempt = cmpxchg ptr %state.address, i32 0, i32 1 acquire monotonic");
		_output.AppendLine("  %acquired = extractvalue { i32, i1 } %attempt, 1");
		_output.AppendLine("  br i1 %acquired, label %initialize, label %wait");
		_output.AppendLine("wait:");
		_output.AppendLine("  call void @luma_thread_sleep(i32 1)");
		_output.AppendLine("  br label %acquire");
		_output.AppendLine("initialize:");
		_output.AppendLine("  store atomic ptr @luma_monitor_identity, ptr %owner.address release, align " + compilation.NativePointerSize);
		_output.AppendLine("  store i32 1, ptr %depth.address");
		_output.AppendLine("  ret void");
		_output.AppendLine("}");

		_output.AppendLine("define internal i1 @luma_monitor_exit(ptr %object) {");
		_output.AppendLine("entry:");
		_output.AppendLine("  %monitor = call ptr @luma_monitor_find(ptr %object, i1 false)");
		_output.AppendLine("  %monitor.missing = icmp eq ptr %monitor, null");
		_output.AppendLine("  br i1 %monitor.missing, label %not.owner, label %check.owner");
		_output.AppendLine("check.owner:");
		_output.AppendLine("  %state.address = getelementptr %luma.monitor_entry, ptr %monitor, i32 0, i32 2");
		_output.AppendLine("  %owner.address = getelementptr %luma.monitor_entry, ptr %monitor, i32 0, i32 3");
		_output.AppendLine("  %depth.address = getelementptr %luma.monitor_entry, ptr %monitor, i32 0, i32 4");
		_output.AppendLine("  %owner = load atomic ptr, ptr %owner.address acquire, align " + compilation.NativePointerSize);
		_output.AppendLine("  %is.owner = icmp eq ptr %owner, @luma_monitor_identity");
		_output.AppendLine("  br i1 %is.owner, label %release.recursion, label %not.owner");
		_output.AppendLine("not.owner:");
		_output.AppendLine("  ret i1 false");
		_output.AppendLine("release.recursion:");
		_output.AppendLine("  %old.depth = load i32, ptr %depth.address");
		_output.AppendLine("  %next.depth = sub i32 %old.depth, 1");
		_output.AppendLine("  store i32 %next.depth, ptr %depth.address");
		_output.AppendLine("  %last.release = icmp eq i32 %next.depth, 0");
		_output.AppendLine("  br i1 %last.release, label %unlock.monitor, label %release.user");
		_output.AppendLine("unlock.monitor:");
		_output.AppendLine("  store atomic ptr null, ptr %owner.address release, align " + compilation.NativePointerSize);
		_output.AppendLine("  store atomic i32 0, ptr %state.address release, align 4");
		_output.AppendLine("  br label %release.user");
		_output.AppendLine("release.user:");
		_output.AppendLine("  call void @luma_monitor_table_lock()");
		_output.AppendLine("  %users.address = getelementptr %luma.monitor_entry, ptr %monitor, i32 0, i32 5");
		_output.AppendLine("  %users = load i32, ptr %users.address");
		_output.AppendLine("  %users.next = sub i32 %users, 1");
		_output.AppendLine("  store i32 %users.next, ptr %users.address");
		_output.AppendLine("  %unused = icmp eq i32 %users.next, 0");
		_output.AppendLine("  br i1 %unused, label %unlink.monitor, label %release.done");
		_output.AppendLine("unlink.monitor:");
		_output.AppendLine($"  %raw = ptrtoint ptr %object to {sizeType}");
		_output.AppendLine($"  %hash = urem {sizeType} %raw, {bucketCount}");
		_output.AppendLine("  %bucket.index = trunc " + sizeType + " %hash to i32");
		_output.AppendLine($"  %bucket.address = getelementptr [{bucketCount} x ptr], ptr @luma_monitor_buckets, i32 0, i32 %bucket.index");
		_output.AppendLine("  br label %unlink.lookup");
		_output.AppendLine("unlink.lookup:");
		_output.AppendLine("  %link.address = phi ptr [ %bucket.address, %unlink.monitor ], [ %candidate.next.address, %unlink.advance ]");
		_output.AppendLine("  %candidate = load ptr, ptr %link.address");
		_output.AppendLine("  %candidate.null = icmp eq ptr %candidate, null");
		_output.AppendLine("  br i1 %candidate.null, label %release.done, label %unlink.compare");
		_output.AppendLine("unlink.compare:");
		_output.AppendLine("  %same.entry = icmp eq ptr %candidate, %monitor");
		_output.AppendLine("  br i1 %same.entry, label %unlink.found, label %unlink.advance");
		_output.AppendLine("unlink.advance:");
		_output.AppendLine("  %candidate.next.address = getelementptr %luma.monitor_entry, ptr %candidate, i32 0, i32 1");
		_output.AppendLine("  br label %unlink.lookup");
		_output.AppendLine("unlink.found:");
		_output.AppendLine("  %entry.next.address = getelementptr %luma.monitor_entry, ptr %monitor, i32 0, i32 1");
		_output.AppendLine("  %entry.next = load ptr, ptr %entry.next.address");
		_output.AppendLine("  store ptr %entry.next, ptr %link.address");
		_output.AppendLine("  call void @free(ptr %monitor)");
		_output.AppendLine("  br label %release.done");
		_output.AppendLine("release.done:");
		_output.AppendLine("  call void @luma_monitor_table_unlock()");
		_output.AppendLine("  call void @luma_thread_critical_exit()");
		_output.AppendLine("  ret i1 true");
		_output.AppendLine("}");
	}

	private void EmitPreserveExceptionRuntime()
	{
		_output.AppendLine("define internal void @luma_throw_preserve(ptr %exception) {");
		_output.AppendLine("entry:");
		_output.AppendLine("  call void @luma_exception_capture_stacktrace(ptr %exception, i1 false)");
		_output.AppendLine("  call void @luma_class_retain_dynamic(ptr %exception)");
		_output.AppendLine("  %previous = load ptr, ptr @luma_pending_exception");
		_output.AppendLine("  %has.previous = icmp ne ptr %previous, null");
		_output.AppendLine("  br i1 %has.previous, label %release.previous, label %set.exception");
		_output.AppendLine("release.previous:");
		_output.AppendLine("  call void @luma_class_release_dynamic(ptr %previous)");
		_output.AppendLine("  br label %set.exception");
		_output.AppendLine("set.exception:");
		_output.AppendLine("  store ptr %exception, ptr @luma_pending_exception");
		_output.AppendLine("  %handler = call ptr @luma_eh_find_handler(ptr %exception)");
		_output.AppendLine("  store ptr %handler, ptr @luma_pending_handler");
		_output.AppendLine("  ret void");
		_output.AppendLine("}");
	}
